import { Inject, Injectable } from "@nestjs/common";
import { and, desc, eq } from "drizzle-orm";
import { schema, withTenant, type Database } from "@mezbaan/db";
import { attachModifiersTo } from "./invoices.service.js";
import { decodeCursor, seekCondition, toPage, type CursorFields, type Page } from "./cursor-pagination.js";
import { DATABASE } from "./db.module.js";
import { computeOrderTotal } from "./orders.service.js";
import { TaxCalculationService } from "./tax-calculation.service.js";

export interface ReconciliationFlagRecord {
  id: string;
  branchId: string;
  invoiceId: string;
  orderId: string;
  storedSubtotalMinor: bigint;
  expectedSubtotalMinor: bigint;
  storedServiceChargeMinor: bigint;
  expectedServiceChargeMinor: bigint;
  storedTaxMinor: bigint;
  expectedTaxMinor: bigint;
  storedTotalMinor: bigint;
  expectedTotalMinor: bigint;
  mismatchedFields: string;
  reviewedAt: Date | null;
  createdAt: Date;
}

export interface ListFlagsParams {
  restaurantId: string;
  branchId?: string;
  limit?: number;
  cursor?: string;
}

const DEFAULT_LIST_LIMIT = 50;
const MAX_LIST_LIMIT = 200;

/**
 * P2-26 (rule 3: "the server recalculates each synced sale and flags any
 * mismatch for review... it never silently changes a recorded sale").
 *
 * `reconcileInvoice` is the outbox handler for the "invoice.generated" event
 * InvoicesService.generate enqueues in the same transaction as the invoice
 * itself (P1-30's convention). It independently recomputes the invoice's
 * totals straight from the order_items currently linked to it — not by
 * reusing anything InvoicesService already held in memory — and compares
 * against what was actually stored. A mismatch becomes an additive row in
 * invoice_reconciliation_flags; the invoice itself is never touched.
 *
 * Today every invoice is generated by this same server process in the same
 * request that computed it, so a genuine mismatch should be rare (a bug, a
 * race, or direct DB tampering) rather than expected — but the same check
 * applies unchanged once an offline terminal's own locally-computed invoice
 * eventually syncs up (P2-45), which is the scenario rule 3 is really
 * describing. The hook point is "an invoice now exists," not "it arrived
 * over a specific transport," so this doesn't need to change when that
 * lands.
 *
 * Rule 14 (a failure here must never block a sale) already holds by
 * construction: this runs asynchronously off the outbox, in a separate
 * process (apps/worker), well after the invoice's own transaction already
 * committed.
 */
@Injectable()
export class ReconciliationService {
  constructor(
    @Inject(DATABASE) private readonly db: Database,
    private readonly taxCalculationService: TaxCalculationService,
  ) {}

  async reconcileInvoice(params: { restaurantId: string; invoiceId: string }): Promise<void> {
    await withTenant(this.db, { restaurantId: params.restaurantId }, async (tx) => {
      const invoiceRows = await tx.select().from(schema.invoices).where(eq(schema.invoices.id, params.invoiceId));
      const invoice = invoiceRows[0];
      if (!invoice) throw new Error(`reconcileInvoice: invoice ${params.invoiceId} not found`);

      const orderRows = await tx.select().from(schema.orders).where(eq(schema.orders.id, invoice.orderId));
      const order = orderRows[0];
      if (!order) throw new Error(`reconcileInvoice: order ${invoice.orderId} for invoice ${invoice.id} not found`);

      // The exact items this invoice covers — not "the whole order," since
      // P2-21's split invoices each bill a disjoint subset. This is the
      // same set InvoicesService.generate itself billed.
      const itemRows = await tx.select().from(schema.orderItems).where(eq(schema.orderItems.invoiceId, invoice.id));
      const items = await attachModifiersTo(tx, itemRows);

      const rawSubtotal = computeOrderTotal(items, invoice.currency);
      const expectedSubtotalMinor = rawSubtotal.amountMinor - (invoice.billDiscountAppliedMinor ?? 0n);

      const expectedCharges = await this.taxCalculationService.previewCharges({
        restaurantId: params.restaurantId,
        branchId: invoice.branchId,
        orderType: order.orderType,
        subtotalMinor: expectedSubtotalMinor,
        currency: invoice.currency,
      });

      const mismatched: string[] = [];
      if (invoice.subtotalMinor !== expectedSubtotalMinor) mismatched.push("subtotal");
      if (invoice.serviceChargeMinor !== expectedCharges.serviceCharge.amountMinor) mismatched.push("serviceCharge");
      if (invoice.taxMinor !== expectedCharges.tax.amountMinor) mismatched.push("tax");
      if (invoice.totalMinor !== expectedCharges.total.amountMinor) mismatched.push("total");

      if (mismatched.length === 0) return;

      await tx.insert(schema.invoiceReconciliationFlags).values({
        restaurantId: params.restaurantId,
        branchId: invoice.branchId,
        invoiceId: invoice.id,
        orderId: invoice.orderId,
        storedSubtotalMinor: invoice.subtotalMinor,
        expectedSubtotalMinor,
        storedServiceChargeMinor: invoice.serviceChargeMinor,
        expectedServiceChargeMinor: expectedCharges.serviceCharge.amountMinor,
        storedTaxMinor: invoice.taxMinor,
        expectedTaxMinor: expectedCharges.tax.amountMinor,
        storedTotalMinor: invoice.totalMinor,
        expectedTotalMinor: expectedCharges.total.amountMinor,
        mismatchedFields: mismatched.join(","),
      });
    });
  }

  async listFlags(params: ListFlagsParams): Promise<Page<ReconciliationFlagRecord>> {
    const limit = Math.min(params.limit ?? DEFAULT_LIST_LIMIT, MAX_LIST_LIMIT);
    const after: CursorFields | undefined = params.cursor !== undefined ? decodeCursor(params.cursor) : undefined;
    const rows = await withTenant(this.db, { restaurantId: params.restaurantId }, (tx) =>
      tx
        .select()
        .from(schema.invoiceReconciliationFlags)
        .where(
          and(
            params.branchId !== undefined ? eq(schema.invoiceReconciliationFlags.branchId, params.branchId) : undefined,
            seekCondition(schema.invoiceReconciliationFlags.createdAt, schema.invoiceReconciliationFlags.id, after),
          ),
        )
        .orderBy(desc(schema.invoiceReconciliationFlags.createdAt), desc(schema.invoiceReconciliationFlags.id))
        .limit(limit + 1),
    );
    return toPage(rows, limit, (row) => ({ createdAt: row.createdAt, id: row.id }));
  }
}
