import { Body, Controller, Get, Post, UseGuards } from "@nestjs/common";
import { DeviceSchema, RedeemPairingCodeSchema, type Device, type DeviceTokenResponse } from "@mezbaan/contracts";
import { CurrentDevice, DeviceAuthGuard } from "./device-auth.guard.js";
import { DeviceService, type DeviceRecord } from "./device.service.js";
import { parseOrBadRequest } from "./validation.js";

function toDeviceResponse(device: DeviceRecord): Device {
  return DeviceSchema.parse({
    id: device.id,
    branchId: device.branchId,
    label: device.label,
    deviceType: device.deviceType,
    status: device.status,
    lastSeenAt: device.lastSeenAt ? device.lastSeenAt.toISOString() : null,
    createdAt: device.createdAt.toISOString(),
  });
}

/** Terminal side (mounted in api-pos): redeem a pairing code for a device token,
 * and a heartbeat/self-check endpoint. The admin side (create a device, generate a
 * pairing code, revoke) is DevicesAdminController, mounted in api-admin instead. */
@Controller("devices")
export class DevicesTerminalController {
  constructor(private readonly deviceService: DeviceService) {}

  /** No auth at all — a terminal has no device token yet at this point. The pairing
   * code, generated by an authenticated admin, is itself the proof of authorization;
   * see DeviceService.redeemPairingCode. */
  @Post("pair")
  async pair(@Body() body: unknown): Promise<DeviceTokenResponse> {
    const { pairingCode } = parseOrBadRequest(RedeemPairingCodeSchema, body);
    const result = await this.deviceService.redeemPairingCode(pairingCode);
    return { deviceToken: result.deviceToken, device: toDeviceResponse(result.device) };
  }

  /** A terminal's way to confirm its stored token still works and fetch its own
   * label/branch — also doubles as the lastSeenAt heartbeat (see validateDeviceToken). */
  @Get("me")
  @UseGuards(DeviceAuthGuard)
  async me(@CurrentDevice() device: DeviceRecord): Promise<Device> {
    return toDeviceResponse(device);
  }
}
